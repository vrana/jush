<?php
// Usage: php compile.php [module ...]
// Concatenates modules/jush.js with modules/jush-<module>.js of the listed modules (all by default) to jush.js.
$modules = array_slice($argv, 1);
$filenames = glob("modules/jush-*.js");
$file = "// @generated from modules/*.js\n";
if ($modules) {
	$filenames = array();
	foreach ($modules as $module) {
		$filename = "modules/jush-$module.js";
		if (!is_file($filename)) {
			fwrite(STDERR, "Unknown module $module, available: " . implode(" ", preg_replace('~^modules/jush-(.*)\.js$~', '$1', glob("modules/jush-*.js"))) . "\n");
			exit(1);
		}
		$filenames[] = $filename;
	}
	$file = "// @generated by php compile.php " . implode(" ", $modules) . "\n";
}
$file .= file_get_contents("modules/jush.js");
foreach ($filenames as $filename) {
	$file .= "\n\n\n" . file_get_contents($filename);
}
file_put_contents('jush.js', $file);
